THREE = {"A": "ALA", "C": "CYS", "D": "ASP", "E": "GLU", "F": "PHE", "G": "GLY", "H": "HIS", "I": "ILE",
         "K": "LYS", "L": "LEU", "M": "MET", "N": "ASN", "P": "PRO", "Q": "GLN", "R": "ARG", "S": "SER",
         "T": "THR", "V": "VAL", "W": "TRP", "Y": "TYR"}


def _atoms(chain, sequence, x0, z, serial):
    lines = []
    for i, aa in enumerate(sequence):
        x = x0 + 3.8 * i
        atoms = [("N", x, 0.0), ("CA", x + 1.2, 0.8), ("C", x + 2.4, 0.0), ("O", x + 2.4, -1.2)]
        if aa != "G":
            atoms.append(("CB", x + 1.2, 2.0))
        for name, ax, ay in atoms:
            serial += 1
            lines.append(f"ATOM  {serial:5d}  {name:<3s} {THREE[aa]} {chain}{i + 1:4d}    "
                         f"{ax:8.3f}{ay:8.3f}{z:8.3f}  1.00 20.00           {name[0]}")
    return lines, serial


def _complex_pdb(antigen_raw_z: float, antigen_shift: float, c_z: float = 60.0,
                 vhh: str = VHH, antigen: str = "A" * 18) -> str:
    """VHH H at z=0; antigen A generated by a -shift z translation; far chain C."""
    head = ["REMARK   2 RESOLUTION.    2.00 ANGSTROMS.",
            "REMARK 350 BIOMOLECULE: 1",
            "REMARK 350 AUTHOR DETERMINED BIOLOGICAL UNIT: TRIMERIC",
            "REMARK 350 APPLY THE FOLLOWING TO CHAINS: H, C",
            "REMARK 350   BIOMT1   1  1.000000  0.000000  0.000000        0.00000",
            "REMARK 350   BIOMT2   1  0.000000  1.000000  0.000000        0.00000",
            "REMARK 350   BIOMT3   1  0.000000  0.000000  1.000000        0.00000",
            "REMARK 350 APPLY THE FOLLOWING TO CHAINS: A",
            "REMARK 350   BIOMT1   2  1.000000  0.000000  0.000000        0.00000",
            "REMARK 350   BIOMT2   2  0.000000  1.000000  0.000000        0.00000",
            f"REMARK 350   BIOMT3   2  0.000000  0.000000  1.000000 {-antigen_shift:14.5f}"]
    body, serial = _atoms("H", vhh, 0.0, 0.0, 0)
    more, serial = _atoms("A", antigen, 3.8, antigen_raw_z, serial)
    body += more + ["TER"]
    more, serial = _atoms("C", "A" * 10, 0.0, c_z, serial)
    body += more
    return "\n".join(head + body + ["TER", "END"]) + "\n"


