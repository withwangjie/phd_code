def _sabdab(**over):
    row = dict(pdb="9abc", Hchain="B", Lchain="NA", antigen_chain="A", antigen_type="protein",
               antigen_name="thing", date="07/29/26", resolution="2.1", method="X-RAY DIFFRACTION", scfv="False")
    row.update(over)
    return row


def test_metadata_gate_mirrors_training_vhh_rules():
    cutoff = dt.date(2026, 1, 1)
    ok = sel.metadata_gate("9abc", [_sabdab()], released_after=cutoff, excluded=set(), max_resolution=3.0)
    assert ok["reasons"] == [] and ok["vhh_chains"] == ["B"] and ok["release_date"] == "2026-07-29"
    two_vhh = sel.metadata_gate("9abc", [_sabdab(), _sabdab(Hchain="C")], released_after=cutoff,
                                excluded=set(), max_resolution=3.0)
    assert two_vhh["reasons"] == [] and two_vhh["vhh_chains"] == ["B", "C"]
    fab = sel.metadata_gate("9abc", [_sabdab(), _sabdab(Hchain="H", Lchain="L")], released_after=cutoff,
                            excluded=set(), max_resolution=3.0)
    assert "contains_vh_vl_antibody" in fab["reasons"]
    old = sel.metadata_gate("9abc", [_sabdab(date="2025-06-01", resolution="NA", antigen_type="carbohydrate")],
                            released_after=cutoff, excluded={"9abc"}, max_resolution=3.0)
    assert {"released_before_cutoff", "unknown_resolution", "non_protein_antigen", "in_study_universe"} <= set(old["reasons"])


def test_independent_groups_use_the_layered_rule_and_structure_clusters():
    base = dict(vhh_sequence=VHH, cdr3="AAGRYGSSWYPDSYDY", antigen_sequences=["MKTAYIAKQRQISFVKSHFSRQ" * 5])
