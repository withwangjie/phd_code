def test_two_pass_preparation_keeps_the_universe_and_pair_table_fixed(tmp_path, monkeypatch):
    import sys
    import torch
    import yaml
    from pathlib import Path as P
    from nanoqc.common.repo_io import sha256_file
    from nanoqc.data import prepare_external_vhh as prep

    monkeypatch.setitem(sys.modules, "anarci", None)
    monkeypatch.setenv("PYTHONPATH", str(P(__file__).resolve().parents[1] / "src"))
    monkeypatch.delenv("QP_EXTERNAL_VHH_SOURCE_DIR", raising=False)
    structures = tmp_path / "structures"
    structures.mkdir()
    (structures / "9zzz.pdb").write_text(_complex_pdb(104.5, 100.0))
    pairs = tmp_path / "pairs.tsv"
    pairs.write_text("query\ttarget\tqtmscore\n1abc\t1abc\t1.0\n9zzz\t9zzz\t1.0\n")
    config = dict(paths=dict(data_root=str(tmp_path / "data"), dataset_dir="dataset"),
                  data_audit=dict(max_resolution_angstrom=3.0),
                  queue_freeze=dict(homology_isolation=dict(vhh_full_chain_identity=0.8, cdr_h3_identity=0.5,
                                                            antigen_identity=0.3, antigen_min_length_coverage=0.7),
                                    independence_clustering=dict(pair_tsv=str(pairs))),
                  external_validation=dict(external_vhh=dict(graph_dir=str(tmp_path / "graphs"),
                                                             source_structure_dir=str(structures), min_clusters=1)))
    config_path = tmp_path / "config.yaml"
    config_path.write_text(yaml.safe_dump(config))
    prep_dir = tmp_path / "prep"
    prep_dir.mkdir()
    (prep_dir / "study_pdb_ids.txt").write_text("1abc\n")
    summary = tmp_path / "sabdab.tsv"
    row = _sabdab(pdb="9zzz", Hchain="H")
    summary.write_text("\t".join(row) + "\n" + "\t".join(row.values()) + "\n")
    common = ["--config", str(config_path), "--prep-dir", str(prep_dir)]
    select = ["--sabdab-summary", str(summary), "--released-after", "2026-01-01"]

    assert prep.main(common + ["pass1", *select]) == 0
    assert (prep_dir / "foldseek_universe.txt").read_text().split() == ["1abc", "9zzz"]
    assert json.loads((prep_dir / "pass1_record.json").read_text())["external_pdb_ids"] == ["9zzz"]

    # A queue_freeze run: non-overlapping training graph + cluster map built from the same pair table.
