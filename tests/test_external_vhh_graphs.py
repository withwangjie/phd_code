def test_external_complex_builds_a_verified_v18_graph(tmp_path, monkeypatch):
    import sys
    monkeypatch.setitem(sys.modules, "anarci", None)  # force the motif fallback
    from nanoqc.data.audit_external_vhh_independence import graph_sequences
    structures = tmp_path / "structures"
    structures.mkdir()
    source = structures / "9zzz.pdb"
    source.write_text(_complex_pdb(antigen_raw_z=104.5, antigen_shift=100.0))

    prepared = ext.prepare_external_complex(source, "H")
    assert prepared["antigen_chains"] == ["A-2"]  # symmetry-generated antigen is kept
    assert {d["chain"] for d in prepared["meta"]["dropped_chains"]} == {"C"}
    assert prepared["meta"]["antigen_contact_basis"] == "whole_vhh_chain_cdr_unmapped"
    assert prepared["cdrs"] == dict(cdr1="", cdr2="", cdr3="AAGRYGSSWYPDSYDY", method="imgt_anchor_motif")
    quality = prepared["quality"]
    assert quality["structure_quality_status"] == "pass", quality
    assert quality["interface_residues"] >= 15

    graph = ext.build_graph(prepared, "9zzz", source)
    assert graph.graph_version == "1.8" and graph.subset_source == "external_vhh"
    assert graph.structure_source == "biological_assembly:author_determined:1"
    import torch
    out = tmp_path / "graphs"
    out.mkdir()
    torch.save(graph, out / "external_vhh__9ZZZ.pt")
    # The formal audit's raw-structure check must rebuild the same assembly.
    record = graph_sequences(out / "external_vhh__9ZZZ.pt", structures)
    assert record["pdb_id"] == "9zzz" and record["cdr_h3"] == "AAGRYGSSWYPDSYDY"
    assert record["vhh"] == [VHH]


